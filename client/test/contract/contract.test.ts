import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { Logger } from '../../src/logger';
import { describeFailures, runEditCase, runMorphCase, type FixtureFile } from './harness';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'fixtures', 'contract');
const files: FixtureFile[] = readdirSync(dir)
    .filter((name) => name.endsWith('.json'))
    .sort()
    .map((name) => JSON.parse(readFileSync(join(dir, name), 'utf-8')) as FixtureFile);

Logger.configure({ enabled: false });

describe('contract fixtures generated by Go', () => {
    it('loads the committed scenarios', () => {
        expect(files.length).toBe(21);
        const cases = files.reduce((n, f) => n + f.cases.length, 0);
        expect(cases).toBeGreaterThan(250);
    });

    for (const file of files) {
        describe(file.scenario, () => {
            it('applies edits strictly to the same DOM the Go model predicts, and keeps node identity', () => {
                const failures = file.cases.flatMap((c) => runEditCase(file.scenario, c));
                expect(failures.length, describeFailures(failures)).toBe(0);
            });

            it('morphs from any state to the reset document and converges on the same DOM and index', () => {
                const failures = file.cases.flatMap((c) => runMorphCase(file.scenario, c));
                expect(failures.length, describeFailures(failures)).toBe(0);
            });
        });
    }
});
